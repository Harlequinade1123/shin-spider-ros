#!/usr/bin/env python3
"""Build Sketch.java from the unmodified original .pde files (+ Golden.inc)."""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]); inc = pathlib.Path(sys.argv[2]); out = pathlib.Path(sys.argv[3])
CLASS_FILES = ["Target", "Motion", "MotionList", "RobotLeg", "RobotHand", "Robot"]
FUNC_FILES = ["leg_motion_commands", "hand_motion_commands"]

def read(n): return (src / (n + ".pde")).read_text(encoding="utf-8")

def strip_method(text, header_re):
    """Remove a method (header regex + brace-matched body)."""
    while True:
        m = re.search(header_re, text)
        if not m: return text
        i = text.index("{", m.end() - 1 if text[m.end()-1] == "{" else m.end())
        depth = 0; j = i
        while True:
            if text[j] == "{": depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0: break
            j += 1
        text = text[:m.start()] + text[j+1:]

main = read("original_spider_controller")
globs = re.search(r"float\[\] leg_links.*?int hand_num\s*=\s*\d+;", main, re.S).group(0)

body = []
body.append("// GENERATED by transform.py - do not edit\n")
body.append("public class Sketch extends Stub {\n")
body.append("  // ---- globals from original_spider_controller.pde ----\n" + globs + "\n")
body.append("  Robot robot;\n  MotionList motion_list;\n")
for n in CLASS_FILES:
    t = read(n)
    t = strip_method(t, r"\n[ \t]*void display\(\)\s*\{")
    body.append(f"// ---- {n}.pde ----\n" + t + "\n")
for n in FUNC_FILES:
    body.append(f"// ---- {n}.pde ----\n" + read(n) + "\n")
body.append(inc.read_text(encoding="utf-8"))
body.append("}\n")
out.write_text("".join(body), encoding="utf-8")
